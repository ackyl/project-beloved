import { S, brush, poly, glow, type Brush } from "./pixels";
import type { Game } from "../game/simulation";

export function annex(c: Brush, g: Game, t: number) {
  const a = g.world.annex;
  c.save();
  c.translate(a.x * S, (a.y - 3) * S);
  const r = brush(c),
    w = 8 * S,
    h = 5 * S;
  r(1, 1, w - 2, h - 2, "#213133");
  r(4, 4, w - 8, h - 8, "#384847");
  for (let i = 5; i < w - 5; i += 14) {
    r(i, 6, 1, h - 11, "#242f32");
    r(i + 1, 7, 1, h - 13, "#56615a");
  }
  r(3, 9, w - 6, 3, "#657368");
  r(4, 14, w - 8, 2, "#243c3d");
  r(2, h - 13, w - 4, 4, "#1d2b2d");
  // Oxidized supply lines and a faded ward stencil run above the equipment.
  r(9, 4, w - 18, 3, "#172c30");
  r(11, 4, w - 22, 1, "#809186");
  for (let i = 12; i < w - 12; i += 21) {
    r(i, 3, 3, 6, "#394e4b");
    r(i, 3, 3, 1, "#8d9986");
  }
  r(14, 22, 19, 22, "#283b3d");
  r(16, 23, 15, 18, "#4e5e55");
  for (let i = 26; i < 40; i += 3) r(18, i, 11, 1, "#293b3b");
  r(118, 23, 23, 11, "#253838");
  r(120, 25, 5, 7, "#9ca390");
  r(119, 27, 8, 2, "#9ca390");
  r(130, 26, 8, 1, "#7d9084");
  r(130, 29, 6, 1, "#7d9084");
  r(88, 11, 24, 4, "#172b2e");
  r(91, 14, 18, 2, "#a4b59b");
  glow(c, 100, 19, 42, "156,216,179", 0.15);
  r(39, 24, 36, 36, "#19282c");
  r(42, 27, 30, 22, "#46655f");
  r(44, 29, 26, 17, "#273f41");
  for (let i = 0; i < 16; i++)
    r(49 + i, 38 + (i % 6 === 3 ? -3 : 0), 1, 1, "#88a396");
  r(46, 53, 5, 3, "#948879");
  r(56, 53, 12, 2, "#556b62");
  r(92, 25, 14, 49, "#25373a");
  r(94, 27, 10, 39, "#5a6e68");
  r(95, 30, 2, 28, "#85968a");
  r(110, 35, 7, 39, "#263b3d");
  r(111, 38, 3, 30, "#758079");
  for (let i = 0; i < 61; i++) {
    const x = 49 + i,
      y = 63 - Math.sin(i * 0.13) * 9 - i * 0.21;
    r(x, y, 2, 2, "#798e7d");
    if (i % 5 === 0) r(x, y - 1, 1, 3, "#bcc3a0");
    if (i % 11 === 0) {
      r(x, y - 5, 1, 5, "#7aa591");
      r(x - 2, y - 6, 5, 2, "#bf99bf");
    }
  }
  // Old lung bellows and their ridged hose are slowly being threaded by roots.
  r(76, 62, 43, 14, "#1c3032");
  r(78, 63, 37, 9, "#58655b");
  r(80, 65, 33, 2, "#829081");
  for (let i = 82; i < 110; i += 4) {
    r(i, 61, 2, 10, "#323f3d");
    r(i, 63, 1, 6, "#8a9482");
  }
  r(75, 76, 48, 3, "#56665b");
  r(79, 79, 3, 7, "#293735");
  r(116, 79, 3, 7, "#293735");
  for (let i = 0; i < 32; i++) {
    const y = 58 + Math.sin((i / 32) * 3.14) * 12;
    r(50 + i, y, 2, 3, i % 3 ? "#405752" : "#84988a");
  }
  for (let i = 0; i < 38; i++) {
    const x = 113 + Math.sin(i * 0.09) * 5,
      y = 29 + i;
    r(x, y, 2, 2, "#718777");
    if (i % 7 === 1) {
      r(x - 3, y - 1, 4, 2, "#929f8b");
      r(x + 1, y - 3, 3, 2, "#b79cb9");
    }
  }
  r(126, 44, 9, 25, "#243738");
  r(128, 46, 5, 19, "#66766a");
  r(129, 47, 2, 12, "#93a292");
  r(3, 84, w - 6, 3, "#293531");
  for (let i = 8; i < w - 8; i += 10) r(i, 84, 5, 1, "#768375");
  r(2, 56, 16, 26, "#162a2c");
  if (!g.panelOpen) {
    r(4, 60, 13, 20, "#5c6b61");
    r(6, 62, 9, 4, "#263e40");
    r(10, 69, 3, 3, "#ddac70");
  } else r(6, 57, 6, 2, "#a7ddad");
  glow(c, 65, 54, 24, "170,145,185", 0.12 + 0.04 * Math.sin(t * 0.06));
  c.restore();
}
